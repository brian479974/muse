// 簡體 → 台灣正體轉換（OpenCC cn→twp 片語級轉換，再套幾條本站用語修正）
import * as OpenCC from 'opencc-js';

const convert = OpenCC.Converter({ from: 'cn', to: 'twp' });
// OpenCC 的正式用字與台灣日常介面用語不同的地方，在這裡統一修正
const fixes = [
  ['臺', '台'],
  // OpenCC 會把「图库」轉成「相簿」（相片集），Muse 指的是素材圖庫
  ['相簿', '圖庫'],
  // 「文胸」是對岸用語，台灣說「胸罩」（2026-11-22 收錄內衣分類時發現 191 處）
  ['文胸', '胸罩'],
  // OpenCC 把頭髮的「发」轉成「發」的幾個髮型詞（2026-11-16 實查素材清單 21 處）
  ['中發', '中髮'],
  ['層次發', '層次髮'],
  ['狼尾發', '狼尾髮'],
  ['水母發', '水母髮'],
  ['溼發', '溼髮'],
  ['撫發', '撫髮'],
  ['撩發', '撩髮'],
  // 篩選欄「全部发长」→ OpenCC 轉成「全部發長」（2026-11-17 截圖時發現，前一天漏修）
  ['發長', '髮長'],
  // 髮型分頁（2026-11-22）：100 款髮型名稱與篩選選項實查，OpenCC 還會把這幾個轉成「發」
  //（現有人物標題也有：低盤發 30、鎖骨發 36、長卷發／大卷發 86 處，一起修正）
  ['盤發', '盤髮'],
  ['綁發', '綁髮'],
  ['骨發', '骨髮'],
  ['肩發', '肩髮'],
  ['卷發', '捲髮'],
  // 介面「上传发型」→ OpenCC 轉成「上傳發型」（「發型」在正體沒有這個詞，一律是髮型）
  ['發型', '髮型'],
  ['型別', '類型'],
  ['自制', '自製'],
  ['賬號', '帳號'],
  ['賬戶', '帳戶'],
  ['獲取', '取得'],
  ['當前', '目前'],
  ['配置', '設定'],
  ['“', '「'],
  ['”', '」'],
  ['‘', '『'],
  ['’', '』'],
  ['質量', '品質'],
  ['服務地址', '服務網址'],
  ['圖片地址', '圖片網址'],
  ['原圖地址', '原圖網址'],
  ['介面地址', '介面網址'],
  // OpenCC 把「声明」轉成程式用語「宣告」；網站法律聲明在台灣慣用「聲明」
  ['網站宣告', '網站聲明'],
  ['關於與宣告', '關於與聲明'],
  ['完整宣告', '完整聲明'],
  ['免責宣告', '免責聲明'],
  // 網站聲明的正式用語：OpenCC 簡轉繁會轉成大陸用詞或錯字
  ['，系自行', '，係自行'],
  ['徑洽', '逕洽'],
  ['IP 地址', 'IP 位址'],
  ['僅保存於使用者', '僅儲存於使用者'],
  ['不會發送至', '不會傳送至'],
];
export function toTw(text) {
  let out = convert(text);
  for (const [from, to] of fixes) out = out.split(from).join(to);
  return out;
}
